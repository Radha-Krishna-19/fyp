#!/usr/bin/env python3
"""build_phase3_data.py -- writes website/phase3_data.js from the Phase 3 output of
code/morphology/run_phase3.py, so the Graph Faces page shows exactly the numbers
the Python code computed (the same pattern as build_real_band_data.py).

Run:  python website/_build/build_phase3_data.py   (after run_phase3.py)
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.abspath(os.path.join(HERE, '..', '..', 'code', 'morphology', 'results', 'phase3_results.json'))
OUT = os.path.abspath(os.path.join(HERE, '..', 'phase3_data.js'))
R = json.load(open(SRC, encoding='utf-8'))
for rec in R.values():
    for f in rec['faces'].values():
        f.pop('terminations', None)          # long per-termination lists are not shown on the page
js = ('/* Generated by _build/build_phase3_data.py from code/morphology/results/phase3_results.json.\n'
      '   Do not edit by hand: re-run run_phase3.py and then this script. */\n'
      'window.PHASE3 = ' + json.dumps(R, indent=1, sort_keys=True) + ';\n')
open(OUT, 'w', encoding='utf-8').write(js)
print('wrote', OUT, len(js), 'bytes')
