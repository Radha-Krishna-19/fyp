"""Write website/general_shape_data.js: the example CIFs for the "Any lattice" section of the
CIF to Shape page, and the Python reference numbers for them.

Run:  python3 website/_build/build_general_shape_data.py   (after code/morphology/run_general_shape.py)
"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
CIFDIR = os.path.join(REPO, 'data', 'structures', 'general_lattice')
RES = os.path.join(REPO, 'code', 'morphology', 'results', 'general_shape.json')
OUT = os.path.join(HERE, '..', 'general_shape_data.js')
# button label, file stem, one line on what the structure is
EXAMPLES = [
    ('Mg-MOF-74', 'MgMOF-74', 'Mg2(dobdc): one-dimensional hexagonal channels along c'),
    ('MIL-53(Cr), narrow pore', 'MIL-53Cr-lt', 'Cr(OH)(bdc): chains of CrO6 octahedra, hydrated narrow-pore form'),
    ('MIL-47(V)', 'MIL-47', 'V(O)(bdc): the same wine-rack net as MIL-53, with vanadium-oxo chains'),
    ('MIL-88A, open', 'MIL-88A-open', 'Fe3O trimers and fumarate, swollen form'),
    ('MIL-88A, dry', 'MIL-88A-dry', 'the same framework, contracted when the solvent leaves'),
    ('ZIF-7', 'ZIF-7', 'Zn and benzimidazolate, trigonal: the same sod net as ZIF-8 with a larger linker'),
    ('MOF-177', 'MOF-177', 'Zn4O and the large three-ended BTB, trigonal'),
    ('MIL-140A', 'MIL-140A', 'Zr: chains of zirconium oxide joined by bdc, monoclinic'),
    ('MOF-5 (cubic)', 'MOF5', 'Zn4O and bdc, cubic: the reference compact crystal. The same file as at the top of the page'),
]


def main():
    py = json.load(open(RES))
    cifs = {stem: open(os.path.join(CIFDIR, stem + '.cif'), encoding='utf-8').read() for _, stem, _ in EXAMPLES}
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('/* Generated by website/_build/build_general_shape_data.py from data/structures/general_lattice/\n'
                '   and code/morphology/results/general_shape.json. Do not edit by hand. */\n')
        f.write('window.GENERAL_EXAMPLES = ' + json.dumps([dict(label=l, stem=s, about=a) for l, s, a in EXAMPLES]) + ';\n')
        f.write('window.GENERAL_CIFS = ' + json.dumps(cifs) + ';\n')
        f.write('window.GENERAL_SHAPE_PY = ' + json.dumps(py) + ';\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
