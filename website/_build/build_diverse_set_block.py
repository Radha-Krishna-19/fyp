"""Write the "Twelve frameworks" block of the Results page (between the diverse-set markers in
website/_build/content_source.html) from data/spectrum_descriptors/size_scaling/diverse_set.json,
written by code/spectrum_pipeline/code_20_diverse_set.py.

Run:  python3 website/_build/build_diverse_set_block.py   (then build_site.py)
"""
import os, json, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(REPO, 'data', 'spectrum_descriptors', 'size_scaling', 'diverse_set.json')
FIG = os.path.join(REPO, 'data', 'spectrum_descriptors', 'size_scaling', 'diverse_set_figure.png')
PAGE = os.path.join(HERE, 'content_source.html')
START, END = '<!-- diverse-set:start -->', '<!-- diverse-set:end -->'


def main():
    R = json.load(open(SRC))
    shutil.copy(FIG, os.path.join(REPO, 'website', 'figures', 'diverse_set_figure.png'))
    fits = {k: v for k, v in R.items() if v['fit']}
    slopes = [v['fit']['slope'] for v in fits.values()]
    r2 = [v['fit']['r2'] for v in fits.values()]
    drift = [v['fit']['drift_last_two'] for v in fits.values()]
    cub = [v['fit']['slope'] for v in fits.values() if v['lattice'] == 'cubic']
    non = [v['fit']['slope'] for v in fits.values() if v['lattice'] != 'cubic']
    rows = []
    for k, v in R.items():
        g, f, sw = v['graph'], v['fit'], v['sweep']
        rows.append('<tr><td class="dt-label">%s</td><td class="dt-note">%s</td><td class="dt-note">%s</td><td class="dt-value">%d / %d</td>'
                    '<td class="dt-value">%s</td><td class="dt-value">%s</td><td class="dt-note">%s</td><td class="dt-value">%s</td><td class="dt-value">%s</td></tr>' % (
                        k, v['node'], v['lattice'], g['node_blocks'], g['linker_blocks'],
                        ', '.join(map(str, g['node_degrees'])),
                        f'{f["slope"]:.3f}' if f else '&mdash;', ('%d&ndash;%d' % (sw[0]['diameter'], sw[-1]['diameter'])) if sw else '&mdash;',
                        f'{f["r2"]:.3f}' if f else '&mdash;', f'{100 * f["drift_last_two"]:.1f} %' if f else '&mdash;'))
    html = f'''{START}
    <h3 class="sub-head" id="diverse-set">Twelve frameworks, not four</h3>
    <p class="sd">The four demonstration nets are all cubic and all have finite clusters as nodes. The same sweep was rerun
      (<code>code/spectrum_pipeline/code_20_diverse_set.py</code>, the same settings) on twelve frameworks that differ in metal
      (Zn, Cu, Zr, Mg, Cr, V, Fe), node (single atom, paddlewheel, Zn<sub>4</sub>O, Zr<sub>6</sub>, Fe<sub>3</sub>O, infinite
      metal&ndash;oxide chains), linker and lattice. The four original slopes are reproduced exactly. On every one of the
      {len(fits)} frameworks with at least three usable supercells, &Delta;&alpha; again grows as a straight line in ln(diameter)
      (R&sup2; {min(r2):.3f}&ndash;{max(r2):.3f}), and the drift between the two largest supercells is {100 * min(drift):.1f}&ndash;{100 * max(drift):.1f} %,
      above the 5 % tolerance everywhere. The slope ranges from {min(slopes):.2f} to {max(slopes):.2f}
      (cubic {min(cub):.2f}&ndash;{max(cub):.2f}; non-cubic {min(non):.2f}&ndash;{max(non):.2f}). The conclusion above therefore does not
      depend on having chosen four cubic nets: no framework in this set gives a &Delta;&alpha; that settles.</p>
    <figure class="fig wide">
      <img src="figures/diverse_set_figure.png" alt="Left: Delta-alpha against graph diameter on a log scale for twelve frameworks, every line rising. Right: the fitted slope for each framework, cubic in blue, non-cubic in orange.">
      <figcaption>&Delta;&alpha; against the diameter of the replicated quotient graph for twelve frameworks (solid: cubic; dashed: non-cubic), and the fitted slope of each.
        Generated by <code>code/spectrum_pipeline/code_20_diverse_set.py</code>; numbers in <code>data/spectrum_descriptors/size_scaling/diverse_set.json</code>.</figcaption>
    </figure>
    <div class="table-wrap">
      <table class="data-table" id="diverse-set-table">
        <thead><tr><td>Structure</td><td>Node</td><td>Lattice</td><td>Node / linker blocks per cell</td><td>Node degree</td><td>Slope, &Delta;&alpha; vs ln(D)</td><td>Diameters</td><td>R&sup2;</td><td>Drift, last two</td></tr></thead>
        <tbody>
          {chr(10).join("          " + r for r in rows).strip()}
        </tbody>
      </table>
    </div>
    <p class="sd">In the four rod MOFs (Mg-MOF-74, MIL-53, MIL-47, MIL-140A) the metal&ndash;oxide chain is infinite; the decomposition cuts it
      into one node block per cell, joined to the next along the chain, so their node degree counts linkers and chain neighbours together.
      A framework with fewer than three supercells above the diameter-8 gate (or below the 25&nbsp;000-vertex cap) has no fitted slope.</p>
    {END}'''
    s = open(PAGE, encoding='utf-8').read()
    if START in s:
        s = s[:s.index(START)] + html + s[s.index(END) + len(END):]
    else:
        raise SystemExit('markers not found in content_source.html')
    open(PAGE, 'w', encoding='utf-8').write(s)
    print('wrote the diverse-set block:', len(R), 'frameworks')


if __name__ == '__main__':
    main()
