"""Write website/advisor_data.js for the Shape Advisor page from the result files of
code/morphology/run_benchmark_mofs.py, run_shape_steering.py, run_shape_adsorption.py and
run_dataset_shapes.py. Run after those scripts, then build_site.py.
"""
import os, json
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
RES = os.path.join(REPO, 'code', 'morphology', 'results')
L = lambda n: json.load(open(os.path.join(RES, n)))
B, S, A, D = L('benchmark_mofs.json'), L('shape_steering.json'), L('shape_adsorption.json'), L('dataset_shapes.json')
GEN = os.path.join(REPO, 'data', 'structures', 'general_lattice')
out = dict(order=list(B['predictions'].keys()), predictions=B['predictions'], per_mof=B['per_mof'],
           face_scores=B['face_scores'], habit_scores=B['habit_scores'], n_records=B['n_records'],
           steering=S['mofs'], adsorption=A['mofs'], probes=A['probes_A'], dataset_summary=D['summary'],
           cifs={'Mg-MOF-74': open(os.path.join(GEN, 'MgMOF-74.cif')).read(), 'MIL-53(Fe)': open(os.path.join(GEN, 'MIL-53Cr-lt.cif')).read()},
           sources=dict(benchmark='code/morphology/run_benchmark_mofs.py', steering='code/morphology/run_shape_steering.py',
                        adsorption='code/morphology/run_shape_adsorption.py', dataset='code/morphology/run_dataset_shapes.py'))
with open(os.path.join(REPO, 'website', 'advisor_data.js'), 'w') as f:
    f.write('/* Generated by website/_build/build_advisor_data.py. Do not edit. */\nwindow.ADVISOR = ' + json.dumps(out, default=str) + ';\n')
print('wrote advisor_data.js', os.path.getsize(os.path.join(REPO, 'website', 'advisor_data.js')) // 1024, 'KB')
