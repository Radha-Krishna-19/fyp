#!/usr/bin/env python3
"""Write website/cif_shape_data.js from code/morphology/results/cif_to_shape.json.

The CIF to Shape page computes everything in the browser from the CIF text. This file
carries the Python reference numbers (run_cif_to_shape.py, with spglib) so that the page
can print, under each step, what the independent Python implementation found.

Run:  python3 website/_build/build_cif_shape_data.py   (after run_cif_to_shape.py)
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'code', 'morphology', 'results', 'cif_to_shape.json')
OUT = os.path.join(HERE, '..', 'cif_shape_data.js')

R = json.load(open(SRC))
keep = {}
for name, r in R.items():
    keep[name] = dict(
        a_conv=r['a_conv'], volume=r['volume'], cubic_transform=r['cubic_transform'],
        centring=r['centring'], symmetry_found_with=r['symmetry_found_with'],
        point_group=r['point_group'], spglib=r['spglib'],
        families=r['families'][:6], bfdh_rates=r['bfdh_rates'], shape=r['shape'],
        structure_factor={k: v['ratio'] for k, v in r['structure_factor'].items()},
        other_families_checked=r['other_families_checked'],
        smallest_margin_other_families=r['smallest_margin_other_families'])
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by website/_build/build_cif_shape_data.py from\n'
            '   code/morphology/results/cif_to_shape.json (code/morphology/run_cif_to_shape.py).\n'
            '   Do not edit by hand. */\n')
    f.write('window.CIF_SHAPE_PY = ' + json.dumps(keep, indent=1) + ';\n')
print('wrote', OUT)
